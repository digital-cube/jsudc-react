import { type ComponentProps, forwardRef } from "react";
import { cn } from "../../lib/utils";

export const inputClass = cn(
  "udc:h-8 udc:w-full udc:min-w-0 udc:rounded-md udc:border udc:border-input udc:bg-surface udc:px-2.5 udc:text-[13px] udc:text-foreground udc:shadow-xs",
  "udc:placeholder:text-muted-foreground/80 udc:transition-[border-color,box-shadow]",
  "udc:focus-visible:border-ring udc:focus-visible:outline-none udc:focus-visible:ring-3 udc:focus-visible:ring-ring/20",
  "udc:disabled:cursor-not-allowed udc:disabled:opacity-50",
  "udc:[&::-webkit-inner-spin-button]:opacity-40",
);

export const Input = forwardRef<HTMLInputElement, ComponentProps<"input">>(function Input(
  { className, ...props },
  ref,
) {
  return <input ref={ref} className={cn(inputClass, className)} {...props} />;
});

/** A native select styled like the inputs: keyboard and test friendly. */
export const NativeSelect = forwardRef<HTMLSelectElement, ComponentProps<"select">>(
  function NativeSelect({ className, children, ...props }, ref) {
    return (
      <select
        ref={ref}
        className={cn(
          inputClass,
          // The chevron is `.select-chevron` in index.css: an arbitrary `bg-[url(…)]` class
          // with quotes inside is not generated by Tailwind.
          "udc-select-chevron udc:appearance-none udc:pr-7",
          className,
        )}
        {...props}
      >
        {children}
      </select>
    );
  },
);
